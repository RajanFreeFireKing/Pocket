#!/usr/bin/env bash
# ==============================================================================
# Solus + StreamVex Core Engine - Automated Keystore & Signing Config Generator
# ==============================================================================
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KEYSTORE_PATH="${ROOT_DIR}/release.keystore"
PROPERTIES_PATH="${ROOT_DIR}/keystore.properties"
KEY_ALIAS="solus_release_key"

echo "=== Solus + StreamVex App Signing Setup ==="

if [[ -f "${PROPERTIES_PATH}" ]]; then
    echo "[INFO] Existing keystore.properties found at: ${PROPERTIES_PATH}"
    echo "       To regenerate, backup or delete that file first."
    exit 0
fi

read -sp "Enter password for new Release Keystore: " KEY_PASS
echo
if [[ -z "${KEY_PASS}" ]]; then
    echo "[ERROR] Keystore password cannot be empty."
    exit 1
fi

echo "[1/2] Generating release keystore: ${KEYSTORE_PATH}..."
keytool -genkeypair -v \
    -keystore "${KEYSTORE_PATH}" \
    -alias "${KEY_ALIAS}" \
    -keyalg RSA \
    -keysize 2048 \
    -validity 10000 \
    -storepass "${KEY_PASS}" \
    -keypass "${KEY_PASS}" \
    -dname "CN=Solus, OU=StreamVex AI, O=LocalMeshAI, L=Bangalore, ST=Karnataka, C=IN"

echo "[2/2] Generating signing config: ${PROPERTIES_PATH}..."
cat <<EOF > "${PROPERTIES_PATH}"
# Generated by scripts/create_release_keystore.sh
storeFile=release.keystore
storePassword=${KEY_PASS}
keyAlias=${KEY_ALIAS}
keyPassword=${KEY_PASS}
EOF

chmod 600 "${KEYSTORE_PATH}" "${PROPERTIES_PATH}"

echo "=================================================================="
echo "[SUCCESS] Release keystore and keystore.properties successfully created!"
echo "          Key store: ${KEYSTORE_PATH}"
echo "          Config:    ${PROPERTIES_PATH}"
echo "          You can now build a signed Release APK using:"
echo "          ./gradlew assembleRelease"
echo "=================================================================="
